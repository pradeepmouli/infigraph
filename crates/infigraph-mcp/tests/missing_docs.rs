#[test]
fn every_printed_hint_is_a_dry_run_create_that_goes_where_it_says() {
    let dir = topic();
    let out = missing(
        dir.path(),
        json!({"base": "main", "visibility": "all", "include_changed": true}),
    );

    let hints: Vec<Value> = out
        .lines()
        .filter_map(|l| l.trim().strip_prefix("doc_entry "))
        .map(|j| serde_json::from_str(j).unwrap_or_else(|e| panic!("{j}: {e}")))
        .collect();
    assert!(hints.len() >= 3, "{out}");
    for hint in &hints {
        assert_eq!(hint["op"], "create");
        let target = hint["target"].as_str().unwrap().to_string();
        let doc = hint["doc_file"].as_str().unwrap().to_string();
        let create = |doc_file: Option<String>| {
            doc_entry(
                dir.path(),
                &Op::Create {
                    target: target.clone(),
                    text: "Words.".into(),
                    doc_file,
                },
                false,
            )
            .unwrap_or_else(|e| panic!("{hint}: {e:#}"))
        };
        let named = create(Some(doc.clone()));
        let chosen = create(None);
        assert!(named.contains("dry run") && named.contains(&doc), "{named}");
        assert!(
            chosen.contains(&doc),
            "create picks another document than the hint says for {target}:\n{chosen}"
        );
    }
    assert_eq!(
        std::fs::read_to_string(dir.path().join("docs/glossary/src.md")).unwrap(),
        SRC_DOC,
        "a hint is a dry run"
    );
}

