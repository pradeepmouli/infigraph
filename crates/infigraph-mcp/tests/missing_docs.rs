// ---- the base ------------------------------------------------------------

mod base {
    use super::*;

    fn repo() -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        git(dir.path(), &["init", "-q", "-b", "main"], FIRST);
        write(dir.path(), "a.txt", "1\n");
        git(dir.path(), &["add", "a.txt"], FIRST);
        git(dir.path(), &["commit", "-q", "-m", "one"], FIRST);
        dir
    }

    fn head(dir: &Path) -> String {
        let out = std::process::Command::new("git")
            .args(["rev-parse", "HEAD"])
            .current_dir(dir)
            .output()
            .unwrap();
        String::from_utf8(out.stdout).unwrap().trim().to_string()
    }

    fn commit_edit(dir: &Path, text: &str, message: &str) {
        write(dir, "a.txt", text);
        git(dir, &["commit", "-q", "-am", message], SECOND);
    }

    fn resolved(dir: &Path, explicit: Option<&str>) -> Result<Base, String> {
        resolve_base(dir, explicit)
    }

    #[test]
    fn an_explicit_base_is_used_as_its_merge_base() {
        let dir = repo();
        let first = head(dir.path());
        git(dir.path(), &["checkout", "-q", "-b", "topic"], SECOND);
        commit_edit(dir.path(), "2\n", "two");

        let got = resolved(dir.path(), Some("main")).unwrap();

        assert_eq!(
            (got.name.as_str(), got.commit.as_str()),
            ("main", first.as_str())
        );
        assert_eq!(
            resolved(dir.path(), Some("HEAD")).unwrap().commit,
            head(dir.path())
        );
    }

    #[test]
    fn an_explicit_base_that_does_not_exist_is_an_error_not_a_fall_through() {
        let dir = repo();

        let why = resolved(dir.path(), Some("nope")).unwrap_err();

        assert!(
            why.contains("nope") && why.contains("not a commit"),
            "{why}"
        );
    }

    #[test]
    fn with_no_upstream_the_default_branch_names_are_tried() {
        let dir = repo();
        git(dir.path(), &["checkout", "-q", "-b", "feat/x"], SECOND);

        let got = resolved(dir.path(), None).unwrap();

        assert_eq!((got.name.as_str(), got.via), ("main", "main"));
    }

    #[test]
    fn a_branch_upstream_comes_before_main() {
        let dir = repo();
        git(dir.path(), &["checkout", "-q", "-b", "integration"], SECOND);
        commit_edit(dir.path(), "int\n", "integration");
        let integration = head(dir.path());
        git(dir.path(), &["checkout", "-q", "-b", "feat/y"], SECOND);
        commit_edit(dir.path(), "y\n", "y");
        git(dir.path(), &["branch", "-q", "-u", "integration"], SECOND);

        let got = resolved(dir.path(), None).unwrap();

        assert_eq!(got.name, "integration");
        assert_eq!(got.via, "the branch's upstream");
        assert_eq!(got.commit, integration);
    }

    #[test]
    fn a_detached_head_falls_back_to_the_default_branch_names() {
        let dir = repo();
        commit_edit(dir.path(), "2\n", "two");
        git(dir.path(), &["checkout", "-q", "--detach"], SECOND);

        let got = resolved(dir.path(), None).unwrap();

        assert_eq!(got.name, "main");
    }

    #[test]
    fn no_candidate_at_all_is_a_loud_error_naming_what_was_tried() {
        let dir = repo();
        git(dir.path(), &["branch", "-q", "-m", "trunk"], SECOND);

        let why = resolved(dir.path(), None).unwrap_err();

        for tried in ["origin/HEAD", "main", "master", "pass `base`"] {
            assert!(why.contains(tried), "{why}");
        }
    }

    #[test]
    fn a_repository_with_no_commit_is_an_error() {
        let dir = tempfile::tempdir().unwrap();
        git(dir.path(), &["init", "-q", "-b", "main"], FIRST);

        assert!(resolved(dir.path(), None)
            .unwrap_err()
            .contains("no commit"));
    }
}

/// `base_project` on a `topic` branch with `files` written, reindexed.
fn topic_with(files: &[(&str, &str)]) -> tempfile::TempDir {
    let dir = base_project();
    git(dir.path(), &["checkout", "-q", "-b", "topic"], SECOND);
    for (file, text) in files {
        write(dir.path(), file, text);
    }
    if !files.is_empty() {
        commit(dir.path(), SECOND, "topic work");
    }
    reindex_code(dir.path());
    dir
}

