//! `missing_docs`: the symbols a diff adds that no glossary entry describes,
//! in directories that already keep a glossary. The counterpart of
//! `stale_docs`: the entry was never written (most often because the code was
//! created in a commit that carried no entry).
//!
//! The project is a tiny Python tree with two glossary documents, one for
//! `src/` and a nested one for `src/billing/`, committed on `main`; the work
//! under test is a `topic` branch (and, for some cases, uncommitted edits).

use std::path::Path;

use serde_json::{json, Value};

use infigraph_docs::doc_entry::{run as doc_entry, Op};
use infigraph_docs::missing_docs::{resolve_base, Base};
use infigraph_mcp::tools::doc_sync::tool_missing_docs;

mod support;

use support::docs::{code_project, git, index_documents, reindex_code, write};

const FIRST: &str = "2024-01-01T00:00:00Z";
const SECOND: &str = "2024-02-01T00:00:00Z";

const SRC_DOC: &str = "# Glossary\n\n\
### `src/app.py::compute_total`\n\nSums the items in a loop.\n\n\
### `src/app.py::Cart::add`\n\nAppends to the cart.\n";

const BILLING_DOC: &str = "# Billing\n\n\
### `src/billing/invoice.py::total`\n\nThe invoice total.\n";

const INVOICE: &str = "def total(lines):\n    result = 0\n    for line in lines:\n        result += line\n    return result\n";

/// Public, undocumented, four lines: `topic` edits it, which is not an add.
const OLD_PLAIN: &str = "def undocumented_old(x):\n    y = x + 1\n    z = y * 2\n    return z\n";

const NEW_CODE: &str = "\n\ndef apply_discount(total, percent):\n    factor = 1 - percent / 100\n    discounted = total * factor\n    return discounted\n\n\ndef _internal(x):\n    a = x\n    b = a\n    return b\n\n\ndef tiny():\n    return 1\n";

const FOUR_LINES: &str = "    a = 1\n    b = 2\n    return a + b\n";

fn commit(dir: &Path, date: &str, message: &str) {
    let present: Vec<&str> = ["src", "lib", "docs"]
        .into_iter()
        .filter(|d| dir.join(d).exists())
        .collect();
    git(dir, &[&["add"], &present[..]].concat(), date);
    git(dir, &["commit", "-q", "-m", message], date);
}

fn base_project() -> tempfile::TempDir {
    let dir = code_project(
        &[
            ("src/billing/invoice.py", INVOICE),
            ("src/old.py", OLD_PLAIN),
            ("lib/util.py", "def helper():\n    return 1\n"),
        ],
        &[
            ("docs/glossary/src.md", SRC_DOC),
            ("docs/glossary/billing.md", BILLING_DOC),
        ],
    );
    index_documents(dir.path());
    git(dir.path(), &["init", "-q", "-b", "main"], FIRST);
    commit(dir.path(), FIRST, "base");
    dir
}

/// The `topic` branch: new public, private and tiny functions in `src/`, a
/// refund in the nested glossary's directory, a test, two generated files, a
/// function in a directory with no glossary, and an edit to an undocumented
/// old function.
fn topic() -> tempfile::TempDir {
    let dir = base_project();
    let root = dir.path();
    git(root, &["checkout", "-q", "-b", "topic"], SECOND);
    let app = std::fs::read_to_string(root.join("src/app.py")).unwrap();
    write(root, "src/app.py", &format!("{app}{NEW_CODE}"));
    write(
        root,
        "src/billing/refund.py",
        "def refund(order):\n    amount = order.total\n    order.total = 0\n    return amount\n",
    );
    write(
        root,
        "src/test_cart.py",
        &format!("def check_cart_totals():\n{FOUR_LINES}"),
    );
    write(
        root,
        "src/api_pb2.py",
        &format!("def build_message():\n{FOUR_LINES}"),
    );
    write(
        root,
        "src/gen_client.py",
        &format!("# Code generated by tool. DO NOT EDIT.\ndef fetch():\n{FOUR_LINES}"),
    );
    write(
        root,
        "lib/util.py",
        &format!("def helper():\n    return 1\n\n\ndef brand_new_helper():\n{FOUR_LINES}"),
    );
    write(
        root,
        "src/old.py",
        &OLD_PLAIN.replace("z = y * 2", "z = y * 3"),
    );
    commit(root, SECOND, "topic work");
    reindex_code(root);
    index_documents(root);
    dir
}

fn missing(dir: &Path, args: Value) -> String {
    let mut args = args;
    args["path"] = json!(dir.to_string_lossy());
    tool_missing_docs(&args).unwrap_or_else(|e| panic!("{args}: {e:#}"))
}

/// The symbol ids a report lists (a line `file:N  kind id`).
fn listed(out: &str) -> Vec<String> {
    out.lines()
        .filter_map(|l| {
            let (_, rest) = l.trim().split_once("  ")?;
            let (kind, id) = rest.split_once(' ')?;
            matches!(kind, "function" | "method" | "class")
                .then(|| id.split("  [").next().unwrap_or(id).trim().to_string())
        })
        .collect()
}

fn has(out: &str, id: &str) -> bool {
    listed(out).iter().any(|i| i == id)
}

/// The part of a report under one document's heading.
fn under<'a>(out: &'a str, doc: &str) -> &'a str {
    let after = out.split(&format!("{doc} (")).nth(1).unwrap_or("");
    after.split("\n\n").next().unwrap_or(after)
}

