/// A function renamed by editing its `def` line is a change, not an add; when
/// the entry was rekeyed to the new id the file answers "documented" even
/// under `include_changed`, and when it was not, the renamed function shows up
/// as changed (and the old key is `stale_docs`' business, not this report's).
#[test]
fn a_renamed_function_is_a_change_and_a_rekeyed_entry_documents_it() {
    let dir = topic_with(&[]);
    let app = std::fs::read_to_string(dir.path().join("src/app.py")).unwrap();
    write(
        dir.path(),
        "src/app.py",
        &app.replace("def compute_total", "def compute_sum"),
    );
    reindex_code(dir.path());

    let not_rekeyed = missing(dir.path(), json!({"base": "main", "include_changed": true}));
    assert!(
        has(&not_rekeyed, "src/app.py::compute_sum"),
        "{not_rekeyed}"
    );
    assert!(
        not_rekeyed.contains("[changed, not added]"),
        "{not_rekeyed}"
    );

    write(
        dir.path(),
        "docs/glossary/src.md",
        &SRC_DOC.replace("compute_total", "compute_sum"),
    );
    let rekeyed = missing(dir.path(), json!({"base": "main", "include_changed": true}));
    assert!(!has(&rekeyed, "src/app.py::compute_sum"), "{rekeyed}");
}
